#!/bin/sh
# Refreshes the vendored front-end libraries in public/assets/vendor/ from npm.
# Requires: npm, tar. Run from the repository root:
#   sh tools/vendor-assets.sh
# Versions are pinned below; update them deliberately and review the diff.
#
# SPDX-License-Identifier: AGPL-3.0-or-later
set -eu

BOOTSTRAP=5.3.8
BOOTSTRAP_ICONS=1.13.2
GLIGHTBOX=3.3.1
FONT_ALEGREYA=5.3.0
FONT_GOLOS=5.3.0

ROOT=$(cd "$(dirname "$0")/.." && pwd)
DEST="$ROOT/public/assets/vendor"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

fetch() {
    # fetch <package> <version> -> unpacked into $WORK/<package>/package
    dir="$WORK/$(echo "$1" | tr '/@' '__')"
    mkdir -p "$dir"
    (cd "$dir" && npm pack --silent "$1@$2" >/dev/null && tar xzf ./*.tgz)
    echo "$dir/package"
}

rm -rf "$DEST"
mkdir -p "$DEST"

# Bootstrap: compiled CSS and the JS bundle (with Popper)
src=$(fetch bootstrap "$BOOTSTRAP")
mkdir -p "$DEST/bootstrap/css" "$DEST/bootstrap/js"
cp "$src/dist/css/bootstrap.min.css" "$DEST/bootstrap/css/"
cp "$src/dist/js/bootstrap.bundle.min.js" "$DEST/bootstrap/js/"
cp "$src/LICENSE" "$DEST/bootstrap/LICENSE"

# Bootstrap Icons: icon font
src=$(fetch bootstrap-icons "$BOOTSTRAP_ICONS")
mkdir -p "$DEST/bootstrap-icons/fonts"
cp "$src/font/bootstrap-icons.min.css" "$DEST/bootstrap-icons/"
cp "$src/font/fonts/bootstrap-icons.woff2" "$src/font/fonts/bootstrap-icons.woff" "$DEST/bootstrap-icons/fonts/"
cp "$src/LICENSE" "$DEST/bootstrap-icons/LICENSE"

# GLightbox: lightbox for the item gallery
src=$(fetch glightbox "$GLIGHTBOX")
mkdir -p "$DEST/glightbox/css" "$DEST/glightbox/js"
cp "$src/dist/css/glightbox.min.css" "$DEST/glightbox/css/"
cp "$src/dist/js/glightbox.min.js" "$DEST/glightbox/js/"
cp "$src/LICENSE.md" "$DEST/glightbox/LICENSE.md"

# Fonts (Fontsource): latin, latin-ext, cyrillic and cyrillic-ext subsets, woff2 only
mkdir -p "$DEST/fonts"
FONTS_CSS="$DEST/fonts/fonts.css"
printf '/* Generated by tools/vendor-assets.sh from Fontsource packages. */\n' > "$FONTS_CSS"
add_font() {
    # add_font <npm package> <version> <dir name> <weights...>
    package=$1; version=$2; name=$3; shift 3
    src=$(fetch "$package" "$version")
    mkdir -p "$DEST/fonts/$name"
    cp "$src/LICENSE" "$DEST/fonts/$name/OFL.txt"
    for weight in "$@"; do
        for subset in cyrillic-ext cyrillic latin-ext latin; do
            file="$name-$subset-$weight-normal.woff2"
            cp "$src/files/$file" "$DEST/fonts/$name/"
        done
        # Keep the @font-face blocks of the four subsets, point them to woff2 only
        awk -v name="$name" '
            /^\/\* / { keep = ($0 ~ /-(cyrillic-ext|cyrillic|latin-ext|latin)-[0-9]+-normal \*\//) }
            keep {
                gsub(/url\(\.\/files\//, "url(./" name "/")
                sub(/, url\([^)]*\.woff\) format\(.woff.\)/, "")
                print
            }
        ' "$src/$weight.css" >> "$FONTS_CSS"
    done
}
add_font @fontsource/alegreya "$FONT_ALEGREYA" alegreya 500 700 800
add_font @fontsource/golos-text "$FONT_GOLOS" golos-text 400 500 600 700

echo "Vendored assets refreshed in $DEST"
